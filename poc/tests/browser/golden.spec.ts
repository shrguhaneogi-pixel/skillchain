import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function signIn(page: Page, name: RegExp) {
  await page.goto('/')
  await page.getByRole('button', { name }).click()
}

test('three isolated roles complete real onboarding, assessment, review, suspension and reset', async ({ browser }) => {
  test.setTimeout(180_000)
  const started = Date.now()
  const [admin, hr, applicant] = await Promise.all(Array.from({ length: 3 }, async () => (await browser.newContext()).newPage()))
  const rpcRequests: string[] = []
  for (const page of [admin, hr, applicant]) {
    page.on('request', request => { if (request.url().includes(':8545')) rpcRequests.push(request.url()) })
    page.on('dialog', dialog => void dialog.accept())
  }

  await signIn(admin, /Isha Mehta/)
  await admin.getByRole('button', { name: 'Reset to fresh onboarding' }).click()
  await expect(admin.getByText(/Sign in as HR to submit/)).toBeVisible()
  await signIn(hr, /Arun Rao/)
  await hr.getByRole('link', { name: 'Company', exact: true }).click()
  await hr.getByRole('button', { name: 'Submit documents' }).click()
  await expect(hr.getByText('Synthetic documents submitted for verifier review.')).toBeVisible()
  await expect(hr.getByRole('button', { name: 'Approve displayed commitment' })).toHaveCount(0)

  await signIn(admin, /Isha Mehta/)
  await admin.getByRole('button', { name: 'Run simulated checks' }).click()
  await admin.getByRole('button', { name: 'Approve displayed commitment' }).click()
  await expect(admin.getByText(/Confirmed transaction 0x[a-f0-9]{64}/)).toBeVisible()
  await admin.getByRole('link', { name: 'Open public verification' }).click()
  await expect(admin.getByRole('heading', { name: 'Local Hardhat · 31337' })).toBeVisible()
  await expect(admin.getByText('Verified', { exact: true }).first()).toBeVisible()
  await admin.getByRole('button', { name: 'Check original fixture' }).click()
  await expect(admin.getByText('Match', { exact: true })).toBeVisible()
  await admin.getByRole('button', { name: 'Check one-byte-altered fixture' }).click()
  await expect(admin.getByText('Mismatch', { exact: true })).toBeVisible()

  await hr.getByRole('link', { name: 'Recruitment' }).click()
  await hr.getByRole('button', { name: 'Publish vacancy', exact: true }).click()
  await expect(hr.getByText('Vacancy published.')).toBeVisible()
  await signIn(applicant, /Mira Sen/)
  await applicant.getByRole('button', { name: 'Apply for Project Coordinator' }).click()
  await applicant.getByRole('link', { name: 'Open orientation' }).click()
  await applicant.getByLabel('Time allowance').selectOption('1.5')
  await applicant.getByLabel(/I consent/).check()
  await applicant.getByRole('button', { name: 'Start assessment' }).click()
  await expect(applicant.getByRole('heading', { name: 'Project Coordinator desk' })).toBeVisible()
  const workplaceUrl = applicant.url()
  await applicant.reload()
  await expect(applicant.getByRole('heading', { name: 'Project Coordinator desk' })).toBeVisible()
  expect(applicant.url()).toBe(workplaceUrl)

  await applicant.getByRole('button', { name: 'Edit Coordinate database recovery' }).click()
  await applicant.getByLabel('Assignee').selectOption('developer')
  await applicant.getByLabel('Priority').selectOption('urgent')
  await applicant.getByRole('button', { name: 'Save task' }).click()
  await expect(applicant.getByText(/Database outage · Developer/)).toBeVisible()
  await applicant.getByLabel('Recipient').selectOption('client')
  await applicant.getByLabel('Linked incident').selectOption('demo')
  await applicant.getByLabel('Message', { exact: true }).fill('We can use a no-cost demo fallback if recovery takes longer.')
  await applicant.getByRole('button', { name: 'Send email' }).click()
  await expect(applicant.getByLabel('Message', { exact: true })).toHaveValue('')
  await applicant.getByLabel('Recipient').selectOption('finance')
  await applicant.getByLabel('Linked incident').selectOption('budget')
  await applicant.getByLabel('Message', { exact: true }).fill('Please reconcile the budget discrepancy before we approve spend.')
  await applicant.getByRole('button', { name: 'Send email' }).click()
  await expect(applicant.getByLabel('Message', { exact: true })).toHaveValue('')
  await applicant.getByRole('button', { name: 'Record spend hold' }).click()
  await applicant.getByRole('combobox', { name: 'Demo plan' }).selectOption('no-cost')
  await applicant.getByRole('button', { name: 'Confirm plan' }).click()
  await expect(applicant.getByText('Client plan: no-cost')).toBeVisible()

  await admin.getByRole('link', { name: 'Verifier console' }).click()
  const controller = admin.getByRole('heading', { name: 'Controller view' }).locator('..')
  await controller.getByRole('combobox').selectOption({ label: 'Mira Sen · Level 1' })
  await admin.getByRole('button', { name: 'Pause assessment' }).click()
  await expect(applicant.getByText('The Platform Verifier paused the assessment.')).toBeVisible()
  await admin.getByRole('button', { name: 'Resume assessment' }).click()
  await expect(applicant.getByRole('button', { name: 'Submit assessment' })).toBeEnabled()
  await applicant.getByRole('button', { name: 'Submit assessment' }).click()
  await expect(applicant.getByText(/Assessment submitted/)).toBeVisible()

  const liveApplication = hr.locator('li').filter({ hasText: 'Mira Sen' })
  await liveApplication.getByRole('link', { name: 'Open evidence report' }).click()
  await hr.getByRole('button', { name: 'Inspect evidence: Marked outage urgent' }).click()
  await expect(hr.getByRole('heading', { name: 'Evidence detail' })).toBeVisible()
  await hr.getByLabel('Applicant feedback').fill('Good ownership and a usable client fallback.')
  await hr.getByRole('button', { name: 'Save human decision' }).click()
  await expect(hr.getByText('Decision and feedback saved.')).toBeVisible()
  await applicant.getByRole('link', { name: 'Return to your application' }).click()
  await expect(applicant.getByText(/Good ownership and a usable client fallback/)).toBeVisible()

  await admin.getByRole('button', { name: 'Suspend company' }).click()
  await expect(admin.getByText('Suspended', { exact: true })).toBeVisible()
  await expect(applicant.getByText(/Organization suspended/)).toBeVisible()
  await admin.getByRole('link', { name: 'Open public verification' }).click()
  await expect(admin.getByText('Suspended', { exact: true }).first()).toBeVisible()
  await hr.getByRole('link', { name: 'Recruitment' }).click()
  await hr.getByText('Vacancy settings').click()
  await hr.getByRole('button', { name: 'Publish vacancy again' }).click()
  await expect(hr.getByRole('alert')).toContainText(/Organization is suspended/)

  const stale = await applicant.evaluate(() => JSON.parse(sessionStorage.getItem('skillchain-poc-session')!).token)
  await admin.getByRole('link', { name: 'Verifier console' }).click()
  await admin.getByRole('button', { name: 'Reset to verified baseline' }).click()
  await expect(admin.getByText(/seeded verified vacancy is ready/)).toBeVisible()
  expect((await applicant.request.post('/api/applications', { headers: { authorization: 'Bearer ' + stale } })).status()).toBe(401)
  await signIn(applicant, /Mira Sen/)
  await expect(applicant.getByRole('button', { name: 'Apply for Project Coordinator' })).toBeVisible()
  expect(rpcRequests).toEqual([])
  expect(Date.now() - started).toBeLessThan(180_000)
})
